const strings: Record<Language, Strings> = { en, "pt-BR": ptBR };

let current: Language = "en";

export function setLanguage(lang: Language): void {
  current = strings[lang] ? lang : "en";
  document.documentElement.lang = current;
}

export function language(): Language {
  return current;
}

/** The strings for the current language. */
export function t(): Strings {
  return strings[current];
}

/** The locale dates are written in. */
export function locale(): string {
  return current === "pt-BR" ? "pt-BR" : "en-GB";
}

/** Formats a date in the current locale, without Portuguese abbreviation dots. */
export function formatDate(ms: number, options: Intl.DateTimeFormatOptions): string {
  const text = new Date(ms).toLocaleDateString(locale(), options);
  return current === "pt-BR" ? text.replace(/\./g, "") : text;
}

/** "sábado" → "Sábado", for dates that start a heading. */
export function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
